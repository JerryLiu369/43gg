const m = (
  id: string,
  x: number,
  y: number,
  initial: 0 | 1,
  kind: TileKind = 'mirror',
): Tile => ({ id, x, y, initial, kind });
const s = (
  x: number,
  y: number,
  direction: Source['direction'] = 0,
  color: 1 | 2 = 1,
): Source => ({ x, y, direction, color });
const b = (
  id: string,
  x: number,
  y: number,
  color: Beacon['color'] = 1,
): Beacon => ({ id, x, y, color });
const level = (
  id: string,
  name: string,
  chapter: string,
  description: string,
  tiles: Tile[],
  sources: Source[],
  beacons: Beacon[],
  initialTide: 0 | 1 = 0,
): Level => ({
  id,
  name,
  chapter,
  description,
  size: 7,
  tiles,
  sources,
  beacons,
  initialTide,
});

